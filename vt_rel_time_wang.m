%log₁₀(pτ) = aT^(-1/3) - b, a = 9.15, b = 7.373, p in atm, τ in sec

function ptau = vt_rel_time_wang(T)
% функция расчета времени релаксации CH4-CH4 по эмпирической формуле Вонга-Спрингера

% Вычисление log10(pτ)
log10_p_tau = 9.15 * T^(-1/3) - 7.373;

% Время колебательной релаксации τ * давление [сек * Па]
ptau = 10^log10_p_tau * 101325; % [атм] -> [Па]

end



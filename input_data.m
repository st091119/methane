function data = input_data
% функция для сборки констант и параметров

% константы
data.c = 29979245800;       % скорость света [cм/сек]
data.h = 6.62607015e-34;    % постоянная Планка [Дж*сек]
data.hbar = data.h/(2*pi);  % постоянная Планка, деленная на 2π [Дж*сек]
data.Na = 6.02214076e23;    % постоянная Авогадро [1/моль]
data.R = 8.314462618;       % универсальная газовая постоянная [Дж/моль/К]
data.k = 1.380649e-23;      % постоянная Больцмана [Дж/К]
data.Torr = 133.322;        % [Торр] -> [Па]
 

% колебательная энергия первых и нулевого уровней молекулы CH4 [Дж]
    data.e0001 = 2.2345827413946877e-19;
    data.e0010 = 2.590037363072917e-19;
    data.e0100 = 2.277350920699104e-19;
    data.e1000 = 2.563955328968551e-19;
    data.e0000 = 1.9629561348881426e-19;

% колебательная частота молекулы CH4 по модам (см^(-1))
data.omega = [3025.0, 1582.7, 3156.8, 1367.4];

% энергия диссоциации CH4
D_cm = 36685.823189; % [см^-1]
data.D = D_cm * data.c * data.h; % [Дж] 

% спектроскопические данные молекул [м^-1] из герцберга
data.Be = 0.05252; % 
% фактор симметрии молекул - вообще 12, но у угл газа тут было указано 1, а
% вообще должно быть 2? Проверить.
data.sigma = 6;

% характеристическая вращательная температура молекул [К] 
data.theta_rot = data.h*data.c*data.Be/data.k;

% массы молекул и атомов
mu_c = 12.0116; % [г/моль]
mu_h = 1.00811; % [г/моль]
mu_ch4 = 0.016043; % [кг/моль]

data.m = 2.663732314e-26; % масса молекулы CH4 [кг]

% параметры потенциала Леннарда-Джонса
data.r0 = 3.737e-10; % CH4-CH4 [м] 
data.em = 151.4; % CH4-CH4, epsilon / k [К]

% колебательная энергия и статвес
% Режим спектра:
%   'fast' — промежуточная сетка: квантовые числа I,J,K,L только 0..3 (быстрее STS/FHO).
%   'full' — полная сетка [9,17,9,20] с отсечкой по энергии диссоциации D (как раньше).
spectrum_mode = 'fast';

data.klop = 0;
switch lower(spectrum_mode)
    case 'fast'
        data.lch4 = [4, 4, 4, 4];
    otherwise
        data.lch4 = [9, 17, 9, 20];
end
data.spectrum_mode = spectrum_mode;
data.d = [1, 2, 3, 3]; % степени вырожденности по модам

% Генерация индексов
[I, J, K, L] = ndgrid(1:data.lch4(1), 1:data.lch4(2), 1:data.lch4(3), 1:data.lch4(4));

% Статвеса
stw = (J .* K .* (K + 1) .* L .* (L + 1)) / 4;

% Колебательная энергия
hc = data.h * data.c;
e1234 = hc * ( ...
    data.omega(1) * (I - 1 + data.d(1)/2) + ...
    data.omega(2) * (J - 1 + data.d(2)/2) + ...
    data.omega(3) * (K - 1 + data.d(3)/2) + ...
    data.omega(4) * (L - 1 + data.d(4)/2) );

% Обнуление по порогу D и подсчет klop
mask_valid = e1234 < data.D;
e1234(~mask_valid) = 0;
stw(~mask_valid) = 1;
data.klop = nnz(mask_valid);    

% Индексы состояний (только для e1234 < D)
inds_all = [ (I(:)-1), (J(:)-1), (K(:)-1), (L(:)-1) ];
data.inds = inds_all(mask_valid(:), :);

data.stw = stw(mask_valid);
data.e1234 = e1234(mask_valid);